# shape, validation, canonical answers, determinism

def test_belts_and_kinds():
    assert riddles.BELTS == ("white", "yellow", "orange", "green", "blue")
    for belt in riddles.BELTS:
        ks = riddles.kinds(belt)
        assert ks and len(set(ks)) == len(ks)
    assert len(riddles.kinds("white")) >= 4
    assert len(riddles.kinds("yellow")) >= 4
    assert len(riddles.kinds("orange")) >= 4
    assert len(riddles.kinds("green")) >= 3
    with pytest.raises(riddles.RiddleGenError):
        riddles.kinds("black")
    with pytest.raises(riddles.RiddleGenError):
        riddles.generate_kind("no_such_kind", random.Random(0), 1)


@pytest.mark.parametrize("belt", riddles.BELTS)
def test_every_belt_generates_valid_riddles(belt):
    seen = set()
    for seed in SEEDS:
        d = riddles.generate(belt, random.Random(seed), seed + 1)
        assert set(d) == {"round_id", "title", "statement", "input", "answer_format",
                          "answer", "belt", "kind"}
        assert d["belt"] == belt and d["kind"] in riddles.kinds(belt)
        assert d["round_id"] == seed + 1
        assert d["title"].startswith(f"{belt.capitalize()} belt: ")
        assert "Answer with" in d["statement"]
        r = R.validate(d)  # validate reads only the public fields
        assert r.hash() == hashing.riddle_hash(r.public())
        fmt, a = d["answer_format"], d["answer"]
        assert fmt in hashing.ANSWER_FORMATS
        if fmt == "integer":
            assert isinstance(a, int) and not isinstance(a, bool)
            assert hashing.canonical_answer(a, fmt) == str(a)
            assert hashing.canonical_answer(str(a), fmt) == str(a)
        else:
            assert isinstance(a, str)
            assert hashing.canonical_answer(a, fmt) == a
        seen.add(d["kind"])
    # 30 seeds over at most 4 kinds: every kind of the belt shows up
    assert seen == set(riddles.kinds(belt))


@pytest.mark.parametrize("belt", riddles.BELTS)
def test_same_seed_same_riddle(belt):
    for seed in (0, 1, 17):
        a = riddles.generate(belt, random.Random(seed), 5)
        b = riddles.generate(belt, random.Random(seed), 5)
        assert a == b
    assert riddles.generate(belt, random.Random(1), 5) != riddles.generate(belt, random.Random(2), 5)


def test_generate_picks_kind_with_the_rng():
    rng = random.Random(3)
    expected = rng.choice(riddles.kinds("white"))
    assert riddles.generate("white", random.Random(3), 1)["kind"] == expected


